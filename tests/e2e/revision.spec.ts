import { expect, test } from '@playwright/test'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import path from 'node:path'

test('select a real React element, review before/after, reopen history, and export evidence', async ({ page, request }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const source = path.resolve('work/e2e-project/src/style.css')
  const original = await readFile(source, 'utf8')
  try {
    await page.goto('http://127.0.0.1:45211/#e2e-local-preview-token')
    await page.getByRole('button', { name: '开始第一轮改稿' }).click()
    await page.getByLabel('改稿名称').fill('首页改稿 · 浏览器验收')
    await page.getByLabel('本地开发地址').fill('http://127.0.0.1:45210/')
    await page.getByRole('button', { name: '保存起点，开始改稿' }).click()
    await expect(page.getByText('元素选择已连接', { exact: true })).toBeVisible({ timeout: 30_000 })
    const list = await request.post('http://127.0.0.1:45211/rpc/list', { headers: { authorization: 'Bearer e2e-local-preview-token' }, data: {} })
    const roundId = (await list.json()).value[0].id
    expect((await request.get(`http://127.0.0.1:45210/.dsh-revise/${roundId}/round.json`)).status()).toBe(403)
    expect((await request.get(`http://127.0.0.1:45210/@fs/${path.resolve('work/e2e-project').replaceAll('\\', '/')}/.dsh-revise/${roundId}/round.json?raw`)).status()).toBe(403)
    await page.getByRole('button', { name: '选择元素', exact: true }).click()
    const frame = page.frameLocator('iframe[title="前端实时预览"]')
    await frame.locator('h1').click()
    await expect(page.getByText('已选中 <h1>', { exact: true })).toBeVisible()
    await page.getByLabel('修改意见').fill('将桌面端标题缩小到 60px，并把按钮改成深紫色。')
    await page.getByRole('button', { name: '保存意见', exact: true }).click()
    await expect(page.locator('.rv-note')).toHaveCount(1)
    await expect(page.locator('.rv-note code')).toContainText('src/main.tsx')
    await page.getByRole('button', { name: '发送给 DSH', exact: true }).click()
    await expect(page.locator('.rv-prompt pre')).toContainText('src/main.tsx')
    await page.getByRole('button', { name: '关闭发送窗口' }).click()
    await writeFile(source, original + '\n@media(min-width:701px){h1{font-size:60px}}.hero-cta{background:#635093}\n')
    await expect(frame.locator('h1')).toHaveCSS('font-size', '60px')
    await page.getByRole('button', { name: '采集修改后', exact: true }).click()
    await expect(page.getByRole('img', { name: '修改后截图', exact: true })).toBeVisible({ timeout: 30_000 })
    await expect(page.getByText(/变化像素/)).toBeVisible()
    await page.getByRole('button', { name: '代码差异', exact: true }).click()
    await expect(page.locator('.rv-code pre')).toContainText('font-size:60px')
    await page.getByRole('button', { name: '前后对照', exact: true }).click()
    await page.getByRole('button', { name: '手机视口' }).click()
    await expect(page.getByRole('img', { name: '修改后截图', exact: true })).toBeVisible()
    await expect(page.getByText(/变化像素 [1-9]/)).toBeVisible()
    await page.getByRole('button', { name: '桌面视口' }).click()
    await page.getByRole('button', { name: '接受', exact: true }).click()
    await expect(page.getByRole('button', { name: '完成本轮验收', exact: true })).toBeEnabled()
    await page.getByRole('button', { name: '完成本轮验收', exact: true }).click()
    await expect(page.getByText('这轮改稿已验收完成', { exact: true })).toBeVisible()
    await mkdir('docs/assets', { recursive: true })
    await page.screenshot({ path: 'docs/assets/review-workbench.png', fullPage: true })
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: '导出报告', exact: true }).click()
    const reportDownload = await download
    expect(reportDownload.suggestedFilename()).toMatch(/^revise-.+\.html$/)
    await reportDownload.saveAs('work/sample-report.html')
    const reportPage = await page.context().newPage()
    await reportPage.goto(`file:///${path.resolve('work/sample-report.html').replaceAll('\\', '/')}`)
    await expect(reportPage.getByRole('heading', { name: '修改意见与人工验收' })).toBeVisible()
    expect(await reportPage.locator('img').evaluateAll(images => images.every(image => (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
    await expect(reportPage.locator('img')).toHaveCount(4)
    await reportPage.close()
    await page.goto('http://127.0.0.1:45211/#e2e-local-preview-token')
    await page.getByRole('button', { name: /首页改稿 · 浏览器验收/ }).first().click()
    await expect(page.getByText('这轮改稿已验收完成', { exact: true })).toBeVisible()
    expect(errors).toEqual([])
  } finally { await writeFile(source, original) }
})

test('mobile viewport works and preview API refuses unauthenticated mutation', async ({ page, request }) => {
  const rejected = await request.post('http://127.0.0.1:45211/rpc/list', { data: {} })
  expect(rejected.status()).toBe(403)
  await page.setViewportSize({ width: 750, height: 1100 })
  await page.goto('http://127.0.0.1:45211/#e2e-local-preview-token')
  await page.getByRole('button', { name: '开始第一轮改稿' }).click()
  await page.getByLabel('改稿名称').fill('手机页面元素选择')
  await page.getByLabel('本地开发地址').fill('http://127.0.0.1:45210/')
  await page.getByRole('button', { name: '保存起点，开始改稿' }).click()
  await expect(page.getByText('元素选择已连接', { exact: true })).toBeVisible({ timeout: 30_000 })
  await page.getByRole('button', { name: '手机视口' }).click()
  await expect(page.getByText('元素选择已连接', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '选择元素', exact: true }).click()
  await page.frameLocator('iframe').locator('.hero-cta').click()
  await page.getByLabel('修改意见').fill('让手机端按钮更容易点击。')
  await page.getByRole('button', { name: '保存意见', exact: true }).click()
  await expect(page.locator('.rv-note-viewport')).toContainText('手机')
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 750)
})
